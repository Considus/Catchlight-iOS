#!/usr/bin/env python3
"""Generate the Scene colour palettes from the brand tokens.

    python3 scripts/design/gen_scene_tokens.py                 # regenerate from design/tokens.json
    python3 scripts/design/gen_scene_tokens.py path/tokens.json  # refresh design/tokens.json from a copy, then regenerate
    python3 scripts/design/gen_scene_tokens.py --check         # exit 1 if the generated file is stale

Reads `design/tokens.json` ({"default": ..., "scenes": {id: {"name", "dark", "light"}}})
and writes `Catchlight/UI/Theme/SceneTokens.generated.swift`: the `CatchlightScene` enum
and one palette per Scene and appearance, for the app roles only (the site and icon roles
in the JSON are not used by the app). Standard library only. Never hand-edit the output:
change the JSON and run this again.
"""
import json, os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, 'design', 'tokens.json')
OUTPUT = os.path.join(ROOT, 'Catchlight', 'UI', 'Theme', 'SceneTokens.generated.swift')
ROLES = ['ground', 'surface', 'card', 'raised', 'important', 'line', 'outline', 'text', 'muted', 'faint',
         'accent', 'accentText', 'onAccent', 'lit', 'unlit',
         'field', 'onField', 'fieldMuted', 'iconDot']
HEX = re.compile(r'^#[0-9A-Fa-f]{6}$')
IDENT = re.compile(r'^[a-z][A-Za-z0-9]*$')


def fail(message):
    sys.exit('gen_scene_tokens: ' + message)


def load(path):
    with open(path, encoding='utf-8') as f:
        data = json.load(f)
    scenes = data.get('scenes') or fail('no "scenes" in ' + path)
    default = data.get('default')
    if default not in scenes:
        fail('default %r is not a Scene' % default)
    for sid, scene in scenes.items():
        if not IDENT.match(sid):
            fail('Scene id %r is not a Swift identifier' % sid)
        if not isinstance(scene.get('name'), str) or not scene['name']:
            fail('%s has no name' % sid)
        for appearance in ('dark', 'light'):
            palette = scene.get(appearance) or fail('%s has no %s palette' % (sid, appearance))
            for role in ROLES:
                value = palette.get(role)
                if not isinstance(value, str) or not HEX.match(value):
                    fail('%s %s %s is %r, not #RRGGBB' % (sid, appearance, role, value))
    return default, scenes


def swift_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def palette_literal(palette, indent):
    pad = ' ' * indent
    lines = ['ScenePalette(']
    for i, role in enumerate(ROLES):
        comma = ',' if i < len(ROLES) - 1 else ''
        lines.append('%s    %s: 0x%s%s' % (pad, role, palette[role][1:].upper(), comma))
    lines.append(pad + ')')
    return '\n'.join(lines)


def render(default, scenes):
    out = []
    w = out.append
    w('//')
    w('//  SceneTokens.generated.swift')
    w('//  Catchlight')
    w('//')
    w('//  GENERATED by scripts/design/gen_scene_tokens.py from design/tokens.json.')
    w('//  Do not edit by hand: change the JSON and run the script again.')
    w('//')
    w('')
    w('import Foundation')
    w('')
    w('/// The colour Scenes, in the order the picker lists them.')
    w('enum CatchlightScene: String, CaseIterable, Identifiable, Sendable {')
    for sid in scenes:
        w('    case %s' % sid)
    w('')
    w('    static let `default`: CatchlightScene = .%s' % default)
    w('')
    w('    var id: String { rawValue }')
    w('')
    w('    /// The Scene\'s name. Product names: every language keeps the English.')
    w('    var name: String {')
    w('        switch self {')
    for sid, scene in scenes.items():
        w('        case .%s: return String(localized: %s)' % (sid, swift_string(scene['name'])))
    w('        }')
    w('    }')
    w('')
    w('    /// The palette for one appearance.')
    w('    func palette(dark: Bool) -> ScenePalette {')
    w('        switch (self, dark) {')
    for sid, scene in scenes.items():
        for appearance, flag in (('dark', 'true'), ('light', 'false')):
            w('        case (.%s, %s): return %s' % (sid, flag, palette_literal(scene[appearance], 8)))
    w('        }')
    w('    }')
    w('}')
    w('')
    w('/// One Scene\'s app colour roles in one appearance, as 24-bit RGB.')
    w('struct ScenePalette: Equatable, Sendable {')
    for role in ROLES:
        w('    let %s: UInt32' % role)
    w('}')
    w('')
    return '\n'.join(out)


def main(argv):
    check = '--check' in argv
    paths = [a for a in argv if a != '--check']
    if len(paths) > 1:
        fail('usage: gen_scene_tokens.py [--check] [tokens.json]')
    if paths and check:
        fail('--check reads design/tokens.json only')
    if paths and os.path.abspath(paths[0]) != SOURCE:
        load(paths[0])  # refuse a broken copy before it replaces the vendored one
        shutil.copyfile(paths[0], SOURCE)
    text = render(*load(SOURCE))
    if check:
        try:
            with open(OUTPUT, encoding='utf-8') as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != text:
            print('stale: %s does not match design/tokens.json; run scripts/design/gen_scene_tokens.py'
                  % os.path.relpath(OUTPUT, ROOT))
            return 1
        print('current: %s' % os.path.relpath(OUTPUT, ROOT))
        return 0
    with open(OUTPUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote %s' % os.path.relpath(OUTPUT, ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
